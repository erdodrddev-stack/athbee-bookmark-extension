const dict = { pt, en }

export const lang = computed(() => {
  const l = settings.lang === 'auto' ? navigator.language || 'en' : settings.lang
  return l.toLowerCase().startsWith('pt') ? 'pt' : 'en'
})

export function t(key, vars) {
  // "key_one" holds the singular form, used when n is 1
  if (vars?.n === 1 && (dict[lang.value][key + '_one'] ?? en[key + '_one'])) key += '_one'
  let s = dict[lang.value][key] ?? en[key] ?? key
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k])
  return s
}
